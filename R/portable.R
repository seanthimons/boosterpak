#' Write a portable project setup
#'
#' Generates the files that let a pack-less renv project restore itself on any
#' machine and open without installing anything:
#'
#' * `setup.R` at the project root. Run it once per machine from the project
#'   root with `Rscript --vanilla setup.R` (or `source("setup.R")`). It
#'   activates renv, installs the boosterpak commit that generated it, and calls
#'   [restore_portable_project()]. Commit it.
#' * A managed block in `.Rprofile` (between `# BEGIN boosterpak portable
#'   startup` and `# END boosterpak portable startup`). Opening the project
#'   loads the machine-local library that `setup.R` prepared. Before setup it
#'   installs nothing and prints the `Rscript --vanilla setup.R` hint.
#'
#' renv's own `source("renv/activate.R")` line is removed from `.Rprofile`
#' because its auto-loader downloads renv when a project is opened on a new
#' machine. Other renv commands, such as [renv::activate()] or [renv::init()],
#' can add that line back; run this function again to remove it. Running it
#' again also refreshes the pin.
#'
#' The pin is the commit SHA of the installed boosterpak (`RemoteSha`, written
#' by a GitHub install), so a generated `setup.R` always installs the version
#' that wrote it. A boosterpak installed any other way has no SHA: pass `ref`,
#' a full 40-character commit SHA that is pushed to GitHub and is this version
#' of boosterpak or later. Forks are followed through `RemoteUsername` and
#' `RemoteRepo`.
#'
#' This is the only function that writes these startup files.
#' [restore_project()] and [snapshot_project()] create no startup hooks. Pack
#' projects (a `boosters.toml` file or boosterpak's `.Rprofile` blocks) are
#' refused, because removing their renv activation line would break them.
#'
#' @param root Project root containing `renv/activate.R`.
#' @param ref A full 40-character commit SHA to pin, or `NULL` to use the
#'   installed boosterpak's `RemoteSha`.
#' @param overwrite Whether to replace a `setup.R` that boosterpak did not
#'   generate. A generated one is always refreshed.
#' @param verbose Whether to print routine summaries.
#' @return The paths of the files written, invisibly.
#' @examples
#' \dontrun{
#' renv::init()
#' boosterpak::write_portable_setup()
#' }
#' @export
write_portable_setup <- function(
  root = ".",
  ref = NULL,
  overwrite = FALSE,
  verbose = NULL
) {
  check_verbose(verbose)
  root <- normalizePath(root, winslash = "/", mustWork = TRUE)
  if (!file.exists(file.path(root, "renv", "activate.R"))) {
    cli::cli_abort(c(
      "{.file renv/activate.R} does not exist; this is not an renv project.",
      "i" = "Run {.code renv::init()} first."
    ))
  }
  conflicts <- portable_pack_conflicts(root)
  if (length(conflicts) > 0) {
    cli::cli_abort(c(
      "This is a boosterpak pack project; the portable setup is for projects without packs.",
      stats::setNames(conflicts, rep("x", length(conflicts)))
    ))
  }
  pin <- portable_pin(ref)

  setup_path <- file.path(root, "setup.R")
  if (file.exists(setup_path)) {
    existing <- readLines(setup_path, warn = FALSE)
    if (!is_generated_setup(existing) && !isTRUE(overwrite)) {
      cli::cli_abort(c(
        "{.file setup.R} exists and was not generated by boosterpak.",
        "i" = "Use {.code overwrite = TRUE} to replace it."
      ))
    }
  } else {
    existing <- NULL
  }
  setup_lines <- portable_setup_lines(pin)
  profile <- portable_rprofile_lines(root)

  written <- character()
  if (!identical(existing, setup_lines)) {
    writeLines(setup_lines, setup_path, useBytes = TRUE)
    written <- c(written, "setup.R")
  }
  if (!is.null(profile)) {
    writeLines(profile, file.path(root, ".Rprofile"), useBytes = TRUE)
    written <- c(written, ".Rprofile")
  }

  if (should_emit(verbose)) {
    if (!file.exists(file.path(root, "renv.lock"))) {
      cli::cli_alert_warning(
        "{.file renv.lock} does not exist yet; run {.code snapshot_project()} before using {.file setup.R}."
      )
    }
    if (length(written) == 0) {
      cli::cli_alert_info("Portable setup is already up to date.")
    } else {
      cli::cli_alert_success("Wrote {.file {written}}.")
      cli::cli_alert_info(
        "Commit {.file setup.R}; each machine runs {.code Rscript --vanilla setup.R} once."
      )
    }
  }
  invisible(file.path(root, written))
}

#' Restore a portable project and prepare it to open offline
#'
#' Called by the generated `setup.R` after it has installed boosterpak. Runs
#' [restore_project()], then records which library holds renv for this machine
#' in `renv/local/startup` (ignored by git through `renv/local/.gitignore`).
#' The `.Rprofile` block from [write_portable_setup()] reads that record to open
#' the project without installing anything.
#'
#' @inheritParams restore_project
#' @return The restored package records, invisibly.
#' @export
restore_portable_project <- function(
  root = ".",
  require_binaries = character()
) {
  result <- restore_project(root, require_binaries = require_binaries)
  root <- normalizePath(root, winslash = "/", mustWork = TRUE)
  local <- file.path(root, "renv", "local")
  dir.create(local, showWarnings = FALSE, recursive = TRUE)
  ignore <- file.path(local, ".gitignore")
  if (!file.exists(ignore)) {
    writeLines("*", ignore)
  }
  writeLines(
    c(
      dirname(find.package("renv")),
      R.version$platform,
      portable_r_minor()
    ),
    file.path(local, "startup")
  )
  invisible(result)
}

#' Get the R minor version used to key machine-local startup data
#'
#' @return A string such as `"4.6"`.
#' @noRd
portable_r_minor <- function() {
  paste(
    R.version$major,
    strsplit(R.version$minor, ".", fixed = TRUE)[[1L]][1L],
    sep = "."
  )
}

#' Resolve the boosterpak commit a generated setup pins
#'
#' @param ref A full commit SHA, or `NULL` to use the installed package.
#' @param desc Package description metadata.
#' @return A list with `spec` (GitHub `owner/repo`), `sha`, and `version`.
#' @noRd
portable_pin <- function(
  ref = NULL,
  desc = utils::packageDescription("boosterpak")
) {
  sha <- ref
  if (is.null(sha)) {
    github <- identical(tolower(desc[["RemoteType"]] %||% ""), "github")
    sha <- if (github) desc[["RemoteSha"]] else NULL
    if (is.null(sha) || is.na(sha)) {
      cli::cli_abort(c(
        "Cannot pin boosterpak: the installed copy has no GitHub commit SHA.",
        "i" = "Install it from GitHub, for example {.code pak::pkg_install(\"seanthimons/boosterpak\")}, or pass {.arg ref}."
      ))
    }
  }
  if (
    !is.character(sha) || length(sha) != 1L || !grepl("^[0-9a-f]{40}$", sha)
  ) {
    cli::cli_abort(
      "{.arg ref} must be a full 40-character lowercase commit SHA."
    )
  }
  list(
    spec = self_install_spec(desc),
    sha = sha,
    version = as.character(desc[["Version"]] %||% "unknown")
  )
}

#' Check for the header that marks a generated setup file
#'
#' @param lines Lines of an existing `setup.R`.
#' @return A logical scalar.
#' @noRd
is_generated_setup <- function(lines) {
  length(lines) > 0 && grepl("^# Generated by boosterpak ", lines[[1]])
}

#' Find what makes a project a pack project
#'
#' @param root Project root.
#' @return A character vector of reasons; empty for a pack-less project.
#' @noRd
portable_pack_conflicts <- function(root) {
  reasons <- character()
  if (file.exists(boosters_file(root))) {
    reasons <- c(reasons, "{.file boosters.toml} exists.")
  }
  path <- file.path(root, ".Rprofile")
  lines <- if (file.exists(path)) readLines(path, warn = FALSE) else character()
  owned <- c(
    rprofile_startup_begin_marker(),
    rprofile_repository_marker(),
    rprofile_install_policy_marker(),
    rprofile_repository_reapply_marker(),
    rprofile_line(),
    rprofile_hook_line(),
    legacy_rprofile_line()
  )
  if (any(lines %in% owned)) {
    reasons <- c(
      reasons,
      "{.file .Rprofile} has boosterpak pack startup lines."
    )
  }
  reasons
}

#' Build the updated `.Rprofile` for the portable startup block
#'
#' The block replaces the first renv activation line, or stays where it
#' already is, or goes at the top. Other activation lines are removed and all
#' other lines are kept.
#'
#' @param root Project root.
#' @return The new lines, or `NULL` when `.Rprofile` is already correct.
#' @noRd
portable_rprofile_lines <- function(root) {
  path <- file.path(root, ".Rprofile")
  lines <- if (file.exists(path)) readLines(path, warn = FALSE) else character()
  begin <- rprofile_portable_begin_marker()
  removed <- remove_marked_blocks(lines, begin, rprofile_portable_end_marker())
  if (removed$malformed) {
    cli::cli_abort(c(
      "{.file .Rprofile} has unmatched portable startup markers.",
      "i" = "Remove the {.code {begin}} and {.code {rprofile_portable_end_marker()}} lines by hand, then run this again."
    ))
  }
  activation <- is_rprofile_renv_activation(lines)
  block_start <- which(lines == begin)
  anchor <- if (length(block_start) > 0) {
    block_start[[1]]
  } else if (any(activation)) {
    which(activation)[[1]]
  } else {
    1L
  }
  keep <- removed$keep & !activation
  before <- sum(keep[seq_len(anchor - 1L)])
  updated <- append(lines[keep], portable_startup_block(), after = before)
  if (file.exists(path) && identical(updated, lines)) {
    return(NULL)
  }
  updated
}

#' Build the generated `setup.R`
#'
#' Only what must run before boosterpak exists is spelled out: activate renv,
#' point installs at public Package Manager binaries (a Linux rewrite and
#' platform aliases, so unlisted distributions such as Fedora get binaries),
#' and install the pinned boosterpak. Everything after that is package code in
#' [restore_portable_project()].
#'
#' @param pin Result of `portable_pin()`.
#' @return The lines of `setup.R`.
#' @noRd
portable_setup_lines <- function(pin) {
  hosts <- escape_r_string(paste(
    escape_regex(ppm_default_hosts()),
    collapse = "|"
  ))
  template <- c(
    "# Generated by boosterpak @@VERSION@@. Do not edit; refresh with boosterpak::write_portable_setup().",
    "# Run from the project root: Rscript --vanilla setup.R (or source(\"setup.R\")).",
    "# boosterpak is pinned to the commit that generated this file.",
    "local({",
    "  if (!file.exists(\"renv.lock\") || !file.exists(\"renv/activate.R\")) {",
    "    stop(\"Run setup.R from a project root containing renv.lock and renv/activate.R.\")",
    "  }",
    "  options(",
    "    repos = c(getOption(\"repos\")[names(getOption(\"repos\")) != \"CRAN\"], CRAN = \"@@PPM@@\"),",
    "    renv.config.pak.enabled = TRUE,",
    "    renv.config.autoloader.enabled = TRUE",
    "  )",
    "  Sys.setenv(RENV_PROJECT = getwd())",
    "  source(\"renv/activate.R\")",
    "  # Bootstrap repositories for installing pak and boosterpak. Package code",
    "  # takes over in restore_portable_project().",
    "  repos <- getOption(\"repos\")",
    "  ppm <- \"^(https?://(?:@@HOSTS@@)/[^/]+)\"",
    "  repos <- sub(paste0(ppm, \"/__linux__/[^/]+/\"), \"\\\\1/\", repos, perl = TRUE)",
    "  if (!any(names(repos) == \"CRAN_fallback\")) {",
    "    repos[\"CRAN_fallback\"] <- \"https://cloud.r-project.org\"",
    "  }",
    "  if (identical(R.version$os, \"linux-gnu\")) {",
    "    repos <- sub(paste0(ppm, \"/([^/]+)$\"), \"\\\\1/__linux__/manylinux_2_28/\\\\2\", repos, perl = TRUE)",
    "    options(",
    "      HTTPUserAgent = sprintf(",
    "        \"R/%s R (%s)\",",
    "        getRversion(),",
    "        paste(getRversion(), R.version$platform, R.version$arch, R.version$os)",
    "      )",
    "    )",
    "  }",
    "  options(repos = repos, renv.config.repos.override = repos)",
    "",
    "  if (!requireNamespace(\"pak\", quietly = TRUE)) {",
    "    renv::install(\"pak\", prompt = FALSE)",
    "  }",
    "  if (",
    "    identical(R.version$os, \"linux-gnu\") && is.null(getOption(\"pkg.platforms\")) && !nzchar(Sys.getenv(\"PKG_PLATFORMS\"))",
    "  ) {",
    "    platform <- pak::system_r_platform()",
    "    options(pkg.platforms = unique(c(platform, sub(\"^([^-]+)-[^-]+-\", \"\\\\1-pc-\", platform), \"source\")))",
    "  }",
    "",
    "  ref <- \"@@SHA@@\"",
    "  path <- find.package(\"boosterpak\", quiet = TRUE)",
    "  installed_ref <- if (length(path)) {",
    "    read.dcf(file.path(path, \"DESCRIPTION\"), fields = \"RemoteSha\")[[1L]]",
    "  } else {",
    "    NA_character_",
    "  }",
    "  if (!identical(installed_ref, ref)) {",
    "    if (isNamespaceLoaded(\"boosterpak\")) {",
    "      unloadNamespace(\"boosterpak\")",
    "    }",
    "    renv::install(paste0(\"@@SPEC@@@\", ref), prompt = FALSE)",
    "  }",
    "  boosterpak::restore_portable_project()",
    "})"
  )
  fill <- function(x, key, value) gsub(key, value, x, fixed = TRUE)
  template <- fill(template, "@@VERSION@@", pin$version)
  template <- fill(template, "@@PPM@@", portable_ppm_url())
  template <- fill(template, "@@HOSTS@@", hosts)
  template <- fill(template, "@@SHA@@", pin$sha)
  fill(template, "@@SPEC@@", pin$spec)
}

#' Get the public Package Manager repository generated files use
#'
#' A fixed value, never `BOOSTERPAK_PPM_REPO`, so a private host from the
#' generating session cannot land in a committed file.
#'
#' @return A repository URL.
#' @noRd
portable_ppm_url <- function() {
  "https://p3m.dev/cran/latest"
}

#' Build the managed portable startup block
#'
#' Opening the project must never install anything: it loads the renv library
#' recorded in `renv/local/startup` by [restore_portable_project()], and
#' otherwise prints how to run setup.
#'
#' @return The block lines, markers included.
#' @noRd
portable_startup_block <- function() {
  c(
    rprofile_portable_begin_marker(),
    "# Local defaults; setup.R is the only entry point that installs packages.",
    "local({",
    "  repos <- getOption(\"repos\")",
    sprintf("  repos[\"CRAN\"] <- \"%s\"", portable_ppm_url()),
    "  if (!any(names(repos) == \"CRAN_fallback\")) {",
    "    repos[\"CRAN_fallback\"] <- \"https://cloud.r-project.org\"",
    "  }",
    "  options(repos = repos, renv.config.pak.enabled = TRUE)",
    "",
    "  if (file.exists(\"renv.lock\")) {",
    "    marker <- \"renv/local/startup\"",
    "    startup <- if (file.exists(marker)) readLines(marker, warn = FALSE) else character()",
    "    r_minor <- paste(R.version$major, strsplit(R.version$minor, \".\", fixed = TRUE)[[1L]][1L], sep = \".\")",
    "    ready <- length(startup) == 3L &&",
    "      identical(startup[2:3], c(R.version$platform, r_minor)) &&",
    "      file.exists(file.path(startup[[1L]], \"renv\", \"DESCRIPTION\"))",
    "    if (ready) {",
    "      loadNamespace(\"renv\", lib.loc = startup[[1L]])",
    "      renv::load(project = getwd())",
    "    } else {",
    "      message(\"Run Rscript --vanilla setup.R to prepare this project's environment.\")",
    "    }",
    "  }",
    "})",
    rprofile_portable_end_marker()
  )
}
