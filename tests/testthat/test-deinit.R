test_that("interactive cancellation never mutates the project", {
  root <- withr::local_tempdir()
  writeLines("config", file.path(root, "boosters.toml"))
  selection <- character()
  confirmation <- FALSE
  confirmations <- 0L
  local_mocked_bindings(
    .deinit_is_interactive = function() TRUE,
    .deinit_select_components = function(components) selection,
    .deinit_confirm = function(plan) {
      confirmations <<- confirmations + 1L
      confirmation
    },
    .package = "boosterpak"
  )

  result <- deinit(root = root, verbose = FALSE)

  expect_true(result$cancelled)
  expect_equal(result$selected, character())
  expect_equal(confirmations, 0L)
  expect_true(file.exists(file.path(root, "boosters.toml")))

  selection <- "boosters"
  result <- deinit(root = root, verbose = FALSE)
  expect_true(result$cancelled)
  expect_equal(result$selected, "boosters")
  expect_equal(confirmations, 1L)
  expect_true(file.exists(file.path(root, "boosters.toml")))
})

