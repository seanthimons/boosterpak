test_that("deinit selectors act independently", {
  parent <- withr::local_tempdir()
  project_number <- 0L
  make_project <- function() {
    project_number <<- project_number + 1L
    root <- file.path(parent, paste0("project-", project_number))
    dir.create(root)
    dir.create(file.path(root, "boosters"))
    dir.create(file.path(root, "renv"))
    writeLines("config", file.path(root, "boosters.toml"))
    writeLines("helper", file.path(root, "boosters", "fn_helper.R"))
    writeLines("activate", file.path(root, "renv", "activate.R"))
    writeLines("lock", file.path(root, "renv.lock"))
    writeLines(
      c("# air formatter configuration", ""),
      file.path(root, "air.toml")
    )
    writeLines(
      c(
        boosterpak:::rprofile_startup_block(),
        'source("renv/activate.R")'
      ),
      file.path(root, ".Rprofile")
    )
    root
  }

  root <- make_project()
  result <- deinit(
    root,
    renv = FALSE,
    boosters = TRUE,
    rprofile = FALSE,
    lockfile = FALSE,
    air = FALSE,
    force = TRUE,
    verbose = FALSE
  )
  expect_equal(result$selected, "boosters")
  expect_false(file.exists(file.path(root, "boosters.toml")))
  expect_false(dir.exists(file.path(root, "boosters")))
  expect_true(dir.exists(file.path(root, "renv")))

  root <- make_project()
  result <- deinit(
    root,
    renv = TRUE,
    boosters = FALSE,
    rprofile = FALSE,
    lockfile = FALSE,
    air = FALSE,
    force = TRUE,
    verbose = FALSE
  )
  expect_equal(result$selected, "renv")
  expect_false(dir.exists(file.path(root, "renv")))
  expect_equal(
    readLines(file.path(root, ".Rprofile"), warn = FALSE),
    c(boosterpak:::rprofile_startup_block(), 'source("renv/activate.R")')
  )
  expect_equal(
    unname(result$preserved[[".Rprofile"]]),
    "renv activation preserved by request"
  )

  root <- make_project()
  result <- deinit(
    root,
    renv = FALSE,
    boosters = FALSE,
    rprofile = TRUE,
    lockfile = FALSE,
    air = FALSE,
    force = TRUE,
    verbose = FALSE
  )
  expect_equal(result$selected, "rprofile")
  expect_equal(
    readLines(file.path(root, ".Rprofile"), warn = FALSE),
    'source("renv/activate.R")'
  )

  root <- make_project()
  result <- deinit(
    root,
    renv = FALSE,
    boosters = FALSE,
    rprofile = FALSE,
    lockfile = TRUE,
    air = FALSE,
    force = TRUE,
    verbose = FALSE
  )
  expect_equal(result$selected, "lockfile")
  expect_false(file.exists(file.path(root, "renv.lock")))
  expect_true(dir.exists(file.path(root, "renv")))

  root <- make_project()
  result <- deinit(
    root,
    renv = FALSE,
    boosters = FALSE,
    rprofile = FALSE,
    lockfile = FALSE,
    air = TRUE,
    force = TRUE,
    verbose = FALSE
  )
  expect_equal(result$selected, "air")
  expect_false(file.exists(file.path(root, "air.toml")))
  expect_true(file.exists(file.path(root, "boosters.toml")))
})

test_that("deinit validates roots, selectors, force, and verbose", {
  root <- withr::local_tempdir()
  for (name in c("renv", "boosters", "rprofile", "lockfile", "air", "force")) {
    for (value in list(NA, c(TRUE, FALSE), 1, NULL)) {
      args <- list(root = root, force = TRUE, verbose = FALSE)
      args[name] <- list(value)
      expect_error(do.call(deinit, args), name, fixed = TRUE)
    }
  }
  expect_error(
    deinit(root, force = TRUE, verbose = NA),
    "verbose",
    fixed = TRUE
  )
  expect_error(
    deinit(file.path(root, "missing"), force = TRUE, verbose = FALSE),
    "existing directory",
    fixed = TRUE
  )
})

test_that("default interactive deinit selects actionable components once", {
  root <- withr::local_tempdir()
  dir.create(file.path(root, "boosters"))
  writeLines("config", file.path(root, "boosters.toml"))
  writeLines("lock", file.path(root, "renv.lock"))
  writeLines(
    c(boosterpak:::rprofile_startup_block(), "user <- TRUE"),
    file.path(root, ".Rprofile")
  )
  offered <- NULL
  confirmed <- NULL
  local_mocked_bindings(
    .deinit_is_interactive = function() TRUE,
    .deinit_select_components = function(components) {
      offered <<- components
      c("boosters", "rprofile")
    },
    .deinit_confirm = function(plan) {
      confirmed <<- plan
      TRUE
    },
    .package = "boosterpak"
  )

  result <- deinit(root = root, verbose = FALSE)

  expect_equal(offered, c("boosters", "rprofile", "lockfile"))
  expect_equal(confirmed$selected, c("boosters", "rprofile"))
  normalized_root <- normalizePath(root, winslash = "/")
  expect_equal(
    confirmed$deletions$path,
    file.path(normalized_root, c("boosters.toml", "boosters"))
  )
  expect_equal(
    confirmed$rprofile$path,
    file.path(normalized_root, ".Rprofile")
  )
  expect_true(confirmed$rprofile$changed)
  expect_equal(result$selected, c("boosters", "rprofile"))
  expect_true(file.exists(file.path(root, "renv.lock")))
  expect_equal(readLines(file.path(root, ".Rprofile")), "user <- TRUE")
})

