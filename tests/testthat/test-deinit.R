test_that("deinit removes every unchanged generated Air format", {
  canonical <- c(
    "[format]",
    "line-width = 120",
    "indent-width = 2",
    'indent-style = "space"',
    'line-ending = "auto"',
    "persistent-line-breaks = true",
    "exclude = []",
    "default-exclude = true",
    "skip = []",
    "table = []",
    "default-table = true",
    ""
  )
  marker <- "# Generated by boosterpak; deinit() removes this file only while unchanged."
  formats <- list(
    marked = c(marker, canonical),
    unmarked = canonical,
    historical = c("# air formatter configuration", "")
  )

  parent <- withr::local_tempdir()
  for (name in names(formats)) {
    root <- file.path(parent, name)
    dir.create(root)
    writeLines(formats[[name]], file.path(root, "air.toml"))

    result <- deinit(
      root,
      renv = FALSE,
      boosters = FALSE,
      rprofile = FALSE,
      lockfile = FALSE,
      air = TRUE,
      force = TRUE,
      verbose = FALSE
    )

    expect_equal(result$selected, "air", info = name)
    expect_equal(result$removed, "air.toml", info = name)
    expect_false(file.exists(file.path(root, "air.toml")), info = name)
  }
})

