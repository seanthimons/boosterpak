  writeLines(
    c(boosterpak:::rprofile_startup_block(), "user <- TRUE"),
    file.path(root, ".Rprofile")
  )
  local_mocked_bindings(
    .deinit_unlink = function(path) {
      if (identical(basename(path), "boosters")) {
        return(invisible(1L))
      }
      unlink(path, recursive = TRUE, force = TRUE, expand = FALSE)
    },
    .package = "boosterpak"
  )

  expect_error(
    deinit(
      root,
      renv = FALSE,
      boosters = TRUE,
      rprofile = TRUE,
      lockfile = FALSE,
      air = FALSE,
      force = TRUE,
      verbose = FALSE
    ),
    regexp = "(?s)boosters/.*Successfully removed: boosters.toml",
    perl = TRUE
  )

  expect_false(file.exists(file.path(root, "boosters.toml")))
  expect_true(dir.exists(file.path(root, "boosters")))
  expect_equal(readLines(file.path(root, ".Rprofile")), "user <- TRUE")
})

