test_that("deinit removes all supported project artifacts and nothing else", {
  root <- withr::local_tempdir()
  dir.create(file.path(root, "boosters", "packs"), recursive = TRUE)
  dir.create(file.path(root, "renv", "library"), recursive = TRUE)
  writeLines("[packs]", file.path(root, "boosters.toml"))
  writeLines("helper <- TRUE", file.path(root, "boosters", "fn_helper.R"))
  writeLines("activate", file.path(root, "renv", "activate.R"))
  writeLines("{}", file.path(root, "renv.lock"))
  writeLines(
    c("# air formatter configuration", ""),
    file.path(root, "air.toml")
  )
  writeLines("keep", file.path(root, "analysis.R"))

  call <- withVisible(deinit(root = root, force = TRUE, verbose = FALSE))

  expect_false(call$visible)
  expect_equal(call$value$root, normalizePath(root, winslash = "/"))
  expect_equal(
    call$value$selected,
    c("boosters", "renv", "lockfile", "air")
  )
  expect_equal(
    call$value$removed,
    c("boosters.toml", "boosters/", "renv/", "renv.lock", "air.toml")
  )
  expect_false(call$value$rprofile_changed)
  expect_equal(call$value$preserved, character())
  expect_false(call$value$restart_required)
  expect_false(call$value$cancelled)
  expect_false(file.exists(file.path(root, "boosters.toml")))
  expect_false(dir.exists(file.path(root, "boosters")))
  expect_false(dir.exists(file.path(root, "renv")))
  expect_false(file.exists(file.path(root, "renv.lock")))
  expect_false(file.exists(file.path(root, "air.toml")))
  expect_false(file.exists(file.path(root, ".Rprofile")))
  expect_equal(readLines(file.path(root, "analysis.R")), "keep")
})

test_that("deinit removes managed profile lines and preserves user code", {
  root <- withr::local_tempdir()
