# Runs `code` in a fresh non-interactive R process started in `root`, returning
# combined stdout and stderr. A non-zero exit status is kept as an attribute.
run_r_script <- function(root, code) {
  script <- tempfile(fileext = ".R")
  on.exit(unlink(script), add = TRUE)
  writeLines(code, script)
  rscript <- file.path(
    R.home("bin"),
    if (.Platform$OS.type == "windows") "Rscript.exe" else "Rscript"
  )
  withr::with_dir(
    root,
    suppressWarnings(system2(rscript, c("--vanilla", script), stdout = TRUE, stderr = TRUE))
  )
}

test_that("attach file attaches each package and reports missing ones in one line", {
  skip_on_cran()
  root <- withr::local_tempdir()
  dir.create(file.path(root, "boosters"))
  writeLines(
    boosterpak:::attach_file_lines(c("tools", "boosterpakNoSuchPackage", "utils")),
    file.path(root, "boosters", "attach.R")
  )

  out <- run_r_script(root, c(
    'source(file.path("boosters", "attach.R"))',
    'cat("startup finished\\n")',
    'cat(sprintf("objects: %d\\n", length(ls(all.names = TRUE))))',
    'cat(sprintf("tools attached: %s\\n", "package:tools" %in% search()))'
  ))

  expect_null(attr(out, "status"))
  expect_true("startup finished" %in% out)
  expect_true("objects: 0" %in% out)
  expect_true("tools attached: TRUE" %in% out)
  expect_equal(sum(grepl("^boosterpak: ", out)), 1L)
  expect_true(any(grepl("boosterpakNoSuchPackage", out, fixed = TRUE)))
})

test_that("startup hook still sources fn files when attaching fails", {
  skip_on_cran()
  root <- withr::local_tempdir()
  dir.create(file.path(root, "boosters"))
  writeLines(
    boosterpak:::attach_file_lines("tools"),
    file.path(root, "boosters", "attach.R")
  )
  writeLines(
    "boosterpak_test_fn <- function() TRUE",
    file.path(root, "boosters", "fn_boosterpak_test.R")
  )

  out <- run_r_script(root, c(
    # Every library() call fails, as a broken installed package would.
    'library <- function(...) stop("simulated load failure")',
    boosterpak:::rprofile_startup_block(),
    'cat(sprintf("fn defined: %s\\n", exists("boosterpak_test_fn")))'
  ))

  expect_true("fn defined: TRUE" %in% out)
  expect_true(any(grepl("simulated load failure", out, fixed = TRUE)))
  expect_false(any(grepl("^Error", out)))
})

